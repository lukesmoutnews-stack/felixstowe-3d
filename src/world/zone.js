// The playable region: Felixstowe town centre and seafront as one connected zone.
//
// The rest of the town stays loaded and visible, but is closed off: every road that leaves the zone has a
// physical closure (cones, a ROAD CLOSED sign and barriers, built by world/roadworks.js), and between the
// closures a soft boundary turns the player back (back gardens, fields and the beach have no road to close).
//
// The zone is a band around real streets (corridor centrelines taken from the OSM road data, with a buffer
// wide enough to take in the buildings on both sides and their plots) plus the beach and sea in front of the
// promenade. Data: content/playable-zone.js, generated by tools/build-zone.mjs from the same OSM tiles.

import { PLAYABLE_ZONE } from '../content/playable-zone.js';
import { pointInRing } from '../geo/polygon.js';

const Z = PLAYABLE_ZONE;
// segment list with bounding boxes, for a quick distance test
const SEGS = [];
for (const c of Z.corridors) for (let i = 1; i < c.pts.length; i++) {
  const a = c.pts[i - 1], b = c.pts[i];
  SEGS.push({ a, b, r: c.r, minX: Math.min(a[0], b[0]) - c.r, maxX: Math.max(a[0], b[0]) + c.r, minZ: Math.min(a[1], b[1]) - c.r, maxZ: Math.max(a[1], b[1]) + c.r });
}
const BOX = SEGS.reduce((o, s) => ({ minX: Math.min(o.minX, s.minX), maxX: Math.max(o.maxX, s.maxX), minZ: Math.min(o.minZ, s.minZ), maxZ: Math.max(o.maxZ, s.maxZ) }), { minX: Infinity, maxX: -Infinity, minZ: Infinity, maxZ: -Infinity });

function segDist(x, z, a, b) {
  const dx = b[0] - a[0], dz = b[1] - a[1], L2 = dx * dx + dz * dz || 1;
  const t = Math.max(0, Math.min(1, ((x - a[0]) * dx + (z - a[1]) * dz) / L2));
  return Math.hypot(x - a[0] - dx * t, z - a[1] - dz * t);
}

/** True inside the playable zone (town centre + seafront). */
export function inZone(x, z) {
  if (Z.shore && pointInRing(x, z, Z.shore)) return true;
  if (x < BOX.minX || x > BOX.maxX || z < BOX.minZ || z > BOX.maxZ) return false;
  for (const s of SEGS) { if (x < s.minX || x > s.maxX || z < s.minZ || z > s.maxZ) continue; if (segDist(x, z, s.a, s.b) <= s.r) return true; }
  return false;
}

/** How far inside (positive) or outside (negative) the zone a point is, roughly, in metres (corridors only). */
export function zoneMargin(x, z) {
  let best = -Infinity;
  for (const s of SEGS) best = Math.max(best, s.r - segDist(x, z, s.a, s.b));
  return best;
}

export const ZONE = Z;
export const CLOSURES = Z.closures || [];

// ---- the closure lines ----
// Beyond each closure's barrier line, across a band either side of the road, counts as closed even where that
// ground is still inside the corridor buffer: so driving or walking round the end of a barrier (over a pavement,
// verge or garden) stops at the barrier line, the same as hitting it.
const CL = CLOSURES.map((c) => ({ ...c, half: c.kind === 'foot' ? (c.hw === 'pedestrian' ? 14 : 6) : 16 }));
/** True when (x, z) is past a closure's barrier line (within `slack` metres before it) and across its band. */
export function pastClosure(x, z, slack = 0.3) {
  for (const c of CL) {
    const dx = x - c.x, dz = z - c.z; if (Math.abs(dx) > 30 || Math.abs(dz) > 30) continue;
    const d = dx * c.ux + dz * c.uz, l = -dx * c.uz + dz * c.ux;
    if (d > -slack && d < 18 && Math.abs(l) < c.half) return true;
  }
  return false;
}
/** Where the player may be: inside the zone and not past a closure. */
export function playable(x, z, slack) { return inZone(x, z) && !pastClosure(x, z, slack); }
